def png_chunk(tag, body):
    return (struct.pack("!I",len(body)) + tag + body +
            struct.pack("!I",zlib.crc32(tag+body)&0xFFFFFFFF))

def render(path):
    pixels=bytearray(WIDTH*HEIGHT*3)

    def pixel(x,y,color):
        if x<0 or y<0 or x>=WIDTH or y>=HEIGHT:
            return
        off=(y*WIDTH+x)*3
        pixels[off:off+3]=bytes(color)

    for y in range(HEIGHT):
        yr=y/HEIGHT
        for x in range(WIDTH):
            xr=x/WIDTH
            base=(11+int(12*xr),18+int(14*yr),34+int(25*xr))
            mag=max(0,1-(((x-890)/500)**2+((y-80)/390)**2))
            teal=max(0,1-(((x-240)/570)**2+((y-670)/440)**2))
            pixel(x,y,(min(255,base[0]+int(86*mag)+int(10*teal)),
                       min(255,base[1]+int(24*mag)+int(48*teal)),
                       min(255,base[2]+int(55*mag)+int(38*teal))))

    def box(x0,y0,x1,y1,color):
        x0,x1=max(x0,0),min(x1,WIDTH)
        y0,y1=max(y0,0),min(y1,HEIGHT)
        if x1<=x0 or y1<=y0:return
        line=bytes(color)*(x1-x0)
        for y in range(y0,y1):
            off=(y*WIDTH+x0)*3
            pixels[off:off+len(line)]=line

    def glyph_text(msg,x,y,size,color):
        for char in msg.upper():
            for gy,line in enumerate(FONT.get(char,FONT[" "])):
                for gx,c in enumerate(line):
                    if c=="1":
                        box(x+gx*size,y+gy*size,x+(gx+1)*size,y+(gy+1)*size,color)
            x+=6*size

    # Fine lines and a stylized radar motif, not game art.
    box(0,0,WIDTH,8,(126,232,214))
    box(0,HEIGHT-8,WIDTH,HEIGHT,(238,118,170))
    for radius in (59,111,168):
        r2=radius*radius
        for y in range(max(0,280-radius-2),min(HEIGHT,280+radius+3)):
            dy=y-280
            for x in range(max(0,972-radius-2),min(WIDTH,972+radius+3)):
                d=(x-972)**2+dy*dy
                if abs(d-r2)<radius*2:
                    pixel(x,y,(88,165,179))
    box(770,279,1163,282,(88,165,179))
    box(971,75,974,479,(88,165,179))
    box(959,267,986,292,(244,176,194))
    box(74,116,172,124,(238,118,170))

    glyph_text("GTA 6",72,170,19,(243,250,250))
    glyph_text("ITALIA",77,339,11,(117,239,221))
    glyph_text("PS5 / PS5 PRO",78,445,6,(245,188,202))
    glyph_text("TROFEI - GUIDE - HDR OLED",78,520,4,(214,227,240))
    glyph_text("XFEDERIKO11.GITHUB.IO/GTA-6",78,586,3,(169,192,212))

    rows=b"".join(b"\x00"+pixels[y*WIDTH*3:(y+1)*WIDTH*3] for y in range(HEIGHT))
    raw=zlib.compress(rows,9)
    data=(b"\x89PNG\r\n\x1a\n" +
          png_chunk(b"IHDR",struct.pack("!IIBBBBB",WIDTH,HEIGHT,8,2,0,0,0)) +
          png_chunk(b"IDAT",raw) + png_chunk(b"IEND",b""))
    path=Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_bytes(data)
    return path


