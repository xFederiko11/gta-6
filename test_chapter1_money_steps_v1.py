"""Regression tests for four independently labeled Chapter 1 loot locations."""
from copy import deepcopy
from pathlib import Path
import json
import unittest
from chapter1_money_steps_v1 import ACTIONS, GUIDE_ID, SOURCE, render, validate
from visual_guide_content import enrich

ROOT=Path("_site")
PATH="guide-e-tutorial/soldi-facili-capitolo-1/"
CANON="https://xfederiko11.github.io/gta-6/"+PATH

def guide():
    records=json.loads(Path("data/guide.json").read_text(encoding="utf-8"))["guides"]
    return next(g for g in enrich(records) if g["id"]==GUIDE_ID)

class ChapterOneMoneyStepsTests(unittest.TestCase):
    def test_four_real_locations_twelve_short_actions(self):
        g=guide()
        self.assertTrue(validate(g))
        self.assertEqual(len(g["steps"]),4)
        self.assertEqual(len(g["step_headings"]),4)
        self.assertEqual(len(g["checks"]),4)
        self.assertEqual(len(ACTIONS),4)
        self.assertEqual(sum(len(group) for group in ACTIONS),12)
        self.assertEqual(g["source_url"],SOURCE)
        self.assertTrue(g["spoiler"])
        for n, place in enumerate(("Three Sheets Liquor","Manatee Motel","Corsair Key","South Vice-Dale")):
            self.assertIn(place,g["steps"][n])
            view=render(n)
            self.assertEqual(view.count('class="cash-microstep"'),3)
            self.assertNotIn("<img",view)
            self.assertNotIn("<iframe",view)
        self.assertIn("Recalibration",g["caution"])
        self.assertIn("Tourist Trap",g["caution"])
        self.assertIn("Family Savings",g["benefit"])
        self.assertIn("icona gialla",ACTIONS[0][0])
        self.assertIn("pappagallo",ACTIONS[0][1])
        self.assertIn("generatore",ACTIONS[0][2])
        self.assertIn("6.000 GTA$",g["steps"][-1])
        self.assertIn("stima",g["checks"][-1])
        for bad in (-1,4,400):
            with self.assertRaises(ValueError):
                render(bad)

    def test_lost_precautions_fail_closed(self):
        g=deepcopy(guide())
        g["caution"]="Tutto senza rischi"
        with self.assertRaises(ValueError):
            validate(g)
        g=deepcopy(guide())
        g["steps"].pop()
        with self.assertRaises(ValueError):
            validate(g)

    def test_generated_page_has_full_tutorial_no_unauthorized_photos(self):
        file=ROOT/PATH/"index.html"
        if not file.exists():
            self.skipTest("Generated by site CI")
        page=file.read_text(encoding="utf-8")
        self.assertIn('rel="canonical" href="'+CANON+'"',page)
        self.assertEqual(page.count('class="v-step"'),4)
        self.assertEqual(page.count('class="cash-microsteps"'),4)
        self.assertEqual(page.count('class="cash-microstep"'),12)
        self.assertEqual(page.count('data-photo-source-guide="'+GUIDE_ID+'"'),4)
        self.assertIn('class="v-guide-urgent cash-critical-warning"',page)
        warning=page.split('class="v-guide-urgent cash-critical-warning"',1)[1].split('</p>',1)[0]
        self.assertIn('powerpyx.com/gta-6-tourist-trap-take-up-mattias-offer-walkthrough/',warning)
        self.assertNotIn('href="#avviso-capitolo-1"',warning)
        self.assertIn("Family Savings",page)
        self.assertIn("Tourist Trap",page)
        self.assertIn('data-step-external-evidence="map"',page)
        self.assertEqual(page.count('data-step-video-id="1GtrjKhSwzM"'),1)
        self.assertEqual(page.count('data-step-video-seconds="285"'),1)
        first=page.split('id="passaggio-1"',1)[1].split('id="passaggio-2"',1)[0]
        self.assertIn('data-step-external-evidence="map"',first)
        self.assertIn('data-step-video-seconds="285"',first)
        self.assertIn('soltanto Three Sheets Liquor',first)
        self.assertNotIn('<iframe',page)
        self.assertIn('step-video-opt-in-v1.js?v=',page)
        self.assertNotIn('data-visual-location-image="liquor-store"',page)
        self.assertNotIn('data-visual-proof-image="liquor-store"',page)
        self.assertLess(page.index('cash-critical-warning'),page.index('id="passaggio-1"'))
        for n in range(1,5):
            step=page.split('id="passaggio-'+str(n)+'"',1)[1]
            if n<4:
                step=step.split('id="passaggio-'+str(n+1)+'"',1)[0]
            self.assertEqual(step.count('class="cash-microstep"'),3,n)
            self.assertIn('data-photo-source-step="'+str(n)+'"',step)
            self.assertIn('✓ Controllo:',step)

if __name__=="__main__":
    unittest.main()
