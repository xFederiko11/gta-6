"""Release checks for the owner-supplied Rockstar promotional library."""
from pathlib import Path
from html.parser import HTMLParser
import json
import re
import unittest

from rockstar_gallery_v1 import validate, render, PATH, MIN_ASSETS

ROOT=Path("_site")
URL="https://xfederiko11.github.io/gta-6/"+PATH

class GalleryTests(unittest.TestCase):
    def test_manifest_previews_and_no_claims_of_gameplay_evidence(self):
        manifest=validate()
        self.assertEqual(manifest["asset_count"],len(manifest["assets"]))
        self.assertGreaterEqual(len(manifest["assets"]),MIN_ASSETS)
        self.assertEqual(len({x["preview"] for x in manifest["assets"]}),len(manifest["assets"]))
        self.assertTrue(all(x["credit"]=="Rockstar Games" for x in manifest["assets"]))
        page=render(manifest)
        self.assertEqual(page.count('class="rg-card"'),len(manifest["assets"]))
        self.assertEqual(page.count('Fonte: Rockstar Games'),len(manifest["assets"]))
        self.assertIn("non prova di gameplay",page)
        self.assertIn("non conferiscono una licenza",page)
        self.assertIn('data-rg-filter',page)
        self.assertIn('data-rg-search',page)
        self.assertIn('data-rg-more',page)
        self.assertNotIn('src="/gta-6/assets/rockstar/gta-vi/originals/',page)
        self.assertNotIn('data-visual-proof-image=',page)
        self.assertNotIn('https://raw.githubusercontent.com/',page)

    def test_published_gallery_and_no_raw_originals_in_pages(self):
        filename=ROOT/PATH/"index.html"
        if not filename.exists():
            self.skipTest("Build artifact is generated by CI before full release")
        page=filename.read_text(encoding="utf-8")
        manifest=validate()
        n=len(manifest["assets"])
        self.assertIn('<link rel="canonical" href="'+URL+'"',page)
        self.assertIn('name="description"',page)
        self.assertEqual(page.count("<h1"),1)
        self.assertEqual(page.count('class="rg-card"'),n)
        self.assertEqual(page.count('Fonte: Rockstar Games'),n)
        self.assertIn("/assets/rockstar-gallery-v1.css?v=",page)
        self.assertIn("/assets/rockstar-gallery-v1.js?v=",page)
        self.assertTrue((ROOT/"assets/rockstar/gta-vi/manifest.json").is_file())
        self.assertFalse((ROOT/"assets/rockstar/gta-vi/originals").exists(),
                         "Never package the 200MB originals in GitHub Pages")
        for x in manifest["assets"]:
            path=ROOT/"assets/rockstar/gta-vi"/x["preview"]
            self.assertTrue(path.is_file(),str(path))
            self.assertLess(path.stat().st_size,350_000,str(path))
        sitemap=(ROOT/"sitemap.xml").read_text(encoding="utf-8")
        self.assertIn(URL,sitemap)

    def test_chapter_guides_must_not_inherit_promotional_gallery(self):
        for p in ("salvare-auto/",
                  "guide-e-tutorial/soldi-facili-capitolo-1/",
                  "guide-e-tutorial/veicoli-per-moses/"):
            file=ROOT/p/"index.html"
            if not file.exists():continue
            html=file.read_text(encoding="utf-8")
            self.assertNotIn('data-rockstar-gallery',html,p)
            self.assertNotIn('data-rg-card',html,p)
            self.assertNotIn('class="rg-card"',html,p)

if __name__=="__main__":unittest.main()
